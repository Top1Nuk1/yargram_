/**
 * Адрес самого Yargram — тот, куда ведёт кнопка «Открыть Yargram».
 *
 * Адрес приходит переменной `VITE_APP_URL` на сборке: лендинг статический, и
 * знать что-либо о сервере, кроме этой строки, ему не нужно. Значение попадает
 * в бандл, поэтому лендинг не спрашивает у сети, куда вести, — кнопка работает
 * сразу, даже если сервер сейчас недоступен.
 *
 * Если переменную не задали, берётся `/app` — относительный путь. Так работает
 * тот же сервер: он отдаёт лендинг по корню, а приложение по `/app`. Это
 * удобный вариант по умолчанию для локального запуска и для одного сервера.
 */

/** Адрес приложения без хвостовых слешей. Пусто — значения не было. */
function readAppUrl(): string {
  const raw = import.meta.env.VITE_APP_URL;
  if (typeof raw !== 'string') return '';
  // 🔥 Читаем значение при каждом вызове, а не один раз на уровне модуля:
  // константа запомнила бы первое значение и не поддалась ни тесту, ни смене
  // переменной. Само `import.meta.env` в сборке остаётся статической подстановкой,
  // так что на скорость это не влияет.
  return raw.trim().replace(/\/+$/, '');
}

/**
 * Адрес приложения. Без `VITE_APP_URL` — `/app`: приложение живёт на том же
 * сервере отдельным путём, и такая ссылка работает без настройки.
 */
export function appUrl(): string {
  return readAppUrl() || '/app';
}

/**
 * Ссылка для перехода в Yargram. Обычный `<a>`, а не `fetch`: если адрес
 * недоступен, браузер сам покажет ошибку — и это понятнее, чем собственная
 * проверка «сервер не отвечает».
 */
export function appHref(): string {
  return appUrl();
}
