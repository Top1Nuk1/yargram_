/**
 * Проверка ссылок оформления — фон чата, картинка баннера, аватар.
 *
 * Ссылки в оформлении бывают трёх видов, и все три должны проходить:
 *
 * 1. внешняя ссылка (`https://…`) — человек вписал адрес картинки из интернета;
 * 2. своя загрузка (`/api/uploads/<id>?t=…`) — так выглядит `attachment.url`
 *    сразу после загрузки, без протокола;
 * 3. готовый файл приложения (`/wallpapers/…`) — встроенные обои.
 *
 * 🔥 Одна проверка «начинается с http» ломала вторую и третью: файл уже
 * загружен, фон уже стоит, а профиль отказывался сохраняться. Здесь те же
 * правила, что и на сервере, — чтобы клиент и сервер не расходились.
 */
const EXTERNAL_URL = /^https?:\/\//i;

/**
 * Путь внутри приложения: один ведущий слэш и обычные символы пути.
 * `(?!\/)` отсекает `//host` — это уже чужой сайт, а не наш файл.
 * Подпись (`?t=…`) у своих файлов обязательна, поэтому хвост запроса разрешён.
 */
const IN_APP_PATH = /^\/(?!\/)[A-Za-z0-9._~/-]+(?:\?[^\s]*)?$/;

/** Подходит ли строка на роль ссылки оформления. Пустая строка — «снять». */
export function isDecorativeUrl(value: string): boolean {
  const trimmed = value.trim();
  if (!trimmed) return true;
  return EXTERNAL_URL.test(trimmed) || IN_APP_PATH.test(trimmed);
}
