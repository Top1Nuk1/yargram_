/**
 * Адреса страниц, которые лежат рядом с приложением, но не внутри него.
 *
 * 🔥 Приложение живёт на `/app`, а соглашение — на `/terms` у лендинга. Адрес
 * начинается со слеша и потому считается от корня сайта, а не от `base`
 * сборки: если бы мы собрали его из `import.meta.env.BASE_URL`, то на `/app/`
 * вышел бы `/app/terms`, и страница не открылась бы. Слеш в начале — это
 * именно то, что здесь нужно.
 */
export function termsUrl(): string {
  return '/terms';
}