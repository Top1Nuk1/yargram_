/*
 * Yargram — минимальный service worker.
 *
 * Нужен только для того, чтобы браузер (Chrome/Edge/Android) показал окно
 * «Установить приложение» (PWA). Сам по себе он ничего не кэширует и не
 * перехватывает запросы: обработчик fetch намеренно пустой, поэтому все
 * сетевые запросы идут как обычно и не ломают SPA / HMR / свежие бандлы.
 *
 * Если позже захотим офлайн-режим — дописываем кэш здесь, но аккуратно,
 * чтобы не раздавать пользователям устаревший JS.
 */
self.addEventListener('install', () => {
  // Активируемся сразу, без ожидания закрытия старых вкладок.
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(self.clients.claim());
});

// Пустой fetch-обработчик — критерий установки PWA выполнен, но запросы
// пропускаются в сеть (браузер сам делает fallback на network, т.к. нет
// respondWith).
self.addEventListener('fetch', () => {
  /* no-op */
});
